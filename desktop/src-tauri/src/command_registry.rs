//! Lifted out of `lib.rs` as a macro rather than kept inline, because the
//! list is most of that file: four hundred lines of identifiers around thirty
//! lines of application setup, which is what pushed `lib.rs` onto the desktop
//! file-size ratchet. `generate_handler!` has to expand where the builder is
//! constructed, so this is a macro rather than a function: the tokens land
//! back in `lib.rs`, under its own imports, exactly as if they had been
//! written there.
//!
//! Adding a command is one line here, in the block its module belongs to.

